#!/usr/bin/env python3
"""
Generate a C header (memory_events.h) containing an array of int-arrays,
one per line in events_serial.txt, so your firmware can read one sequence
per call to read_events().
"""

import argparse
import os
import sys

def parse_events(input_file):
    """Return a list of lists of ints, one sub-list per non-empty/non-comment line."""
    sequences = []
    with open(input_file, 'r') as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.strip()
            if not line or line.startswith('#'):
                continue
            parts = [p.strip() for p in line.split(',') if p.strip()]
            try:
                seq = [int(p) for p in parts]
            except ValueError as e:
                print(f"[Line {lineno}] skipping invalid token: {e}", file=sys.stderr)
                continue
            sequences.append(seq)
    return sequences

def write_header(sequences, output_file, guard="MEMORY_EVENTS_H"):
    """Emit memory_events.h with one static array per sequence, plus pointers & lengths."""
    with open(output_file, 'w') as f:
        f.write(f"#ifndef {guard}\n")
        f.write(f"#define {guard}\n\n")
        f.write('#include "config.h"\n')
        f.write("// Auto-generated by generate_memory_data.py from events_serial.txt\n\n")
        # Per-line arrays
        for idx, seq in enumerate(sequences):
            vals = ", ".join(str(v) for v in seq)
            f.write(f"static const event_t memory_event_{idx}[] = {{ {vals} }};\n")
        f.write("\n")
        # Pointer table
        f.write(f"static const event_t *memory_events[] = {{\n")
        for idx in range(len(sequences)):
            f.write(f"    memory_event_{idx},\n")
        f.write("};\n\n")
        # Lengths table
        f.write("static const size_t memory_events_lengths[] = {\n")
        for seq in sequences:
            f.write(f"    {len(seq)},\n")
        f.write("};\n\n")
        # Count
        f.write(f"static const size_t memory_events_count = {len(sequences)};\n\n")
        f.write(f"#endif // {guard}\n")

def main():
    p = argparse.ArgumentParser(
        description="Turn data/events_serial.txt into data/memory_events.h with per-line arrays"
    )
    p.add_argument("-i", "--input",  default="data/events_serial.txt",
                   help="CSV input file (one sequence per line)")
    p.add_argument("-o", "--output", default="data/memory_events.h",
                   help="Header to write")
    args = p.parse_args()

    if not os.path.isfile(args.input):
        print("ERROR: input not found:", args.input, file=sys.stderr)
        sys.exit(1)

    seqs = parse_events(args.input)
    write_header(seqs, args.output)
    print(f"Wrote {len(seqs)} sequences to {args.output}")

if __name__ == "__main__":
    main()
