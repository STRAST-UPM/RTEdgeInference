#!/usr/bin/env python3
import argparse
import csv
import subprocess
import re
import sys
from pathlib import Path

def sanitize(name: str) -> str:
    return "MG_" + "".join(c if c.isalnum() or c == "_" else "_" for c in name)

def main():
    parser = argparse.ArgumentParser(description="Generate models_data.c/.h from TFLite models")
    parser.add_argument("models_dir", help="Directory containing .tflite files")
    parser.add_argument("out_c", help="Output .c file path")
    parser.add_argument("out_h", help="Output .h file path")
    parser.add_argument(
        "--props-csv",
        default=None,
        help="Path to models_props.csv (default: <models_dir>/models_props.csv)",
    )
    args = parser.parse_args()

    models_dir = Path(args.models_dir)
    out_c = Path(args.out_c)
    out_h = Path(args.out_h)

    props_csv = Path(args.props_csv) if args.props_csv else models_dir / "models_props.csv"
    if not props_csv.exists():
        raise SystemExit(f"Missing models_props.csv in {models_dir}")

    out_c.parent.mkdir(parents=True, exist_ok=True)
    out_h.parent.mkdir(parents=True, exist_ok=True)

    # Leer CSV de propiedades
    props = {}
    with open(props_csv, newline="") as f:
        r = csv.DictReader(f)
        for row in r:
            props[row["model_name"]] = row

    # Listar modelos .tflite
    tflites = sorted(models_dir.glob("*.tflite"))
    if not tflites:
        raise SystemExit(f"No .tflite files found in {models_dir}")

    # Validar correspondencia 1-a-1
    for t in tflites:
        if t.stem not in props:
            raise SystemExit(f"Missing CSV entry for model {t.stem}")

    # ---------------- Header ----------------
    with open(out_h, "w") as h:
        h.write(
            "#ifndef MODELS_DATA_H\n#define MODELS_DATA_H\n\n"
            '#include "models_mgr.h"\n\n'
            "extern const model_t  g_models[];\n"
            "extern const size_t   g_models_count;\n\n"
            "#endif // MODELS_DATA_H\n"
        )

    # ---------------- Source ----------------
    with open(out_c, "w") as c:
        c.write("// Auto-generated by gen_models_data.py\n")
        c.write('#include "models_data.h"\n\n')

        for t in tflites:
            p = props[t.stem]
            base = t.stem
            var = sanitize(base)

            # incrustar binario
            xxd = subprocess.check_output(["xxd", "-i", str(t)], text=True)

            # convertir a const
            xxd = xxd.replace("unsigned char", "const unsigned char")

            # detectar símbolo original
            m = re.search(r"const unsigned char\s+([A-Za-z0-9_]+)\[\]\s*=", xxd)
            if not m:
                raise SystemExit(f"Cannot detect xxd symbol name for {t}")
            orig_sym = m.group(1)

            # renombrar símbolo
            xxd = re.sub(rf"\b{re.escape(orig_sym)}\b", var, xxd)

            c.write(xxd)
            c.write("\n")

            exec_time = int(p.get("exec_time_ms", 0))
            threshold = float(p.get("threshold", 0.0))
            c.write(f"static const uint64_t {var}_exec_time = {exec_time}ULL;\n")
            c.write(f"static const float    {var}_threshold = {threshold}f;\n")

            triggers = p.get("triggers", "*").strip()
            if triggers == "*":
                c.write(f"static const event_t  {var}_triggers[] = {{}};\n")
                c.write(f"static const size_t   {var}_trigger_count = 0;\n")
                c.write(f"static const bool     {var}_trigger_all = true;\n\n")
            else:
                vals = [v.strip() for v in triggers.split("|") if v.strip()]
                vals_c = ", ".join(vals)
                c.write(f"static const event_t  {var}_triggers[] = {{ {vals_c} }};\n")
                c.write(f"static const size_t   {var}_trigger_count = {len(vals)};\n")
                c.write(f"static const bool     {var}_trigger_all = false;\n\n")

        c.write("const model_t g_models[] = {\n")
        for t in tflites:
            base = t.stem
            var = sanitize(base)
            c.write(
                f'  {{ .name = "{base}", .data = {var}, .size = sizeof({var}), '
                f'.exec_time = {var}_exec_time, .threshold = {var}_threshold, '
                f'.triggers = {var}_triggers, .trigger_count = {var}_trigger_count, '
                f'.trigger_all = {var}_trigger_all }},\n'
            )
        c.write("};\n")
        c.write("const size_t g_models_count = sizeof(g_models)/sizeof(g_models[0]);\n")

if __name__ == "__main__":
    main()
